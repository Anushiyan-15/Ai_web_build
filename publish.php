        try {
            $m = Mailer::getInstance();
            $m->Username = $email;
            $m->Password = $pass;
            $m->setFrom($email, defined('SITE_NAME') ? SITE_NAME : 'WebCraft AI');
            $m->clearAllRecipients();
            $m->addAddress($to);
            $m->isHTML(true);
            $m->Subject = 'Test mail — your website contact form is ready';
            $m->Body = '<p>Success! Enquiries from your website contact form will arrive here, sent from your Gmail.</p>';
            $m->AltBody = 'Success! Your website contact form Gmail is working.';
            $m->send();
            echo json_encode(['success' => true]);
        } catch (Throwable $e) {
            echo json_encode(['success' => false, 'error' => 'Gmail said: ' . substr($e->getMessage(), 0, 160)]);
        }
        exit;
    }

    // Order details (for final step credentials display)
    if ($_GET['action'] === 'order_details') {
        $oid = clean($_GET['order_id'] ?? '');
        $order = loadOrder($oid);
        if (!$order) { echo json_encode(['success' => false]); exit; }
        echo json_encode([
            'success' => true,
            'order' => [
                'order_id'             => $order['order_id'],
                'live_url'             => $order['live_url'],
                'admin_url'            => $order['admin_url'],
                'admin_username'       => $order['admin_username'],
                'admin_password_plain' => $order['admin_password_plain'] ?? null,
                'subdomain' => $order['subdomain'] ?? '',
                'site_active'          => $order['site_active'] ?? true,
                'next_payment_due'     => $order['next_payment_due'] ?? null,
                'admin_entities'       => $order['admin_entities'] ?? [],
                'gen_mode'             => $order['gen_mode'] ?? 'static',
            ]
        ]);
        exit;
    }

    // Raw chat (fallback to Gemini)
    if ($_GET['action'] === 'raw_chat') {
        $body = json_decode(file_get_contents('php://input'), true) ?: $_POST;
        $prompt = $body['prompt'] ?? '';
        $apiKey = $body['api_key'] ?? (defined('GEMINI_API_KEY') ? GEMINI_API_KEY : '');
        if (!$prompt || !$apiKey) { echo json_encode(['success'=>false,'error'=>'Missing prompt or API key']); exit; }

        $url = 'https://generativelanguage.googleapis.com/v1beta/models/'
             . (defined('GEMINI_MODEL') ? GEMINI_MODEL : 'gemini-2.0-flash')
             . ':generateContent?key=' . urlencode($apiKey);

        $payload = json_encode([
            'contents' => [['parts' => [['text' => $prompt]]]],
            'generationConfig' => ['temperature' => 0.3, 'maxOutputTokens' => 16000]
        ]);

        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
            CURLOPT_POSTFIELDS => $payload,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => 180,
        ]);
        $resp = curl_exec($ch);
        $code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);
        if ($code !== 200) { echo json_encode(['success'=>false,'error'=>"Gemini error $code"]); exit; }
        $j = json_decode($resp, true);
        $text = $j['candidates'][0]['content']['parts'][0]['text'] ?? '';
        echo json_encode(['success' => true, 'text' => $text]);
        exit;
    }
