/* Test owner Gmail SMTP (step-by-step verification before publish) */
async function testOwnerSmtp() {
  const u = (document.getElementById('smtp-user')?.value || '').trim();
  const p = (document.getElementById('smtp-pass')?.value || '').replace(/\s+/g, '');
  const to = (state.contactEmail || state.adminEmail || '').trim();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(u)) { setMsg('smtp-msg', 'Enter your Gmail address first.', 'bad'); return; }
  if (p.length < 8) { setMsg('smtp-msg', 'Paste the 16-letter App Password.', 'bad'); return; }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(to)) { setMsg('smtp-msg', 'Set the inbox email above first (test mail goes there).', 'bad'); return; }
  const btn = document.getElementById('btn-test-smtp');
  if (btn) { btn.disabled = true; btn.textContent = '⏳ Testing…'; }
  setMsg('smtp-msg', 'Connecting to Gmail…', '');
  try {
    const res = await fetch(SITE_URL + '/publish.php?action=test_smtp', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email: u, pass: p, to })
    });
    const j = await res.json();
    if (j.success) {
      state.smtpUser = u; state.smtpPass = p; state.smtpOk = true;
      try {
        const raw = localStorage.getItem(SESSION_KEY);
        if (raw) {
          const s = JSON.parse(raw);
          s.smtpUser = u; s.smtpPass = p;
          localStorage.setItem(SESSION_KEY, JSON.stringify(s));
        }
      } catch (e) {}
      setMsg('smtp-msg', '✓ Gmail works! Test mail sent to ' + to, 'ok');
    } else {
      state.smtpOk = false;
      setMsg('smtp-msg', '❌ ' + (j.error || 'Gmail rejected these details'), 'bad');
    }
  } catch (err) {
    state.smtpOk = false;
    setMsg('smtp-msg', '❌ Network error while testing', 'bad');
  }
  if (btn) { btn.disabled = false; btn.textContent = '✉️ Test Gmail →'; }
}

/* ═══════════════ STEP HANDLERS ═══════════════ */
async function onNext() {
  const btn = document.getElementById('btn-next');

  if (state.step === 1) {
    if (!state.html) { showToast('⚠️ No design found'); return; }
    state.step = nextStep() || state.step;
    renderStep();
    return;
  }

  if (state.step === 2) {
    const ce = (state.contactEmail || '').trim();
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(ce)) {
      setMsg('contact-email-msg', 'Enter the inbox email for your leads — required.', 'bad');
      document.getElementById('contact-email')?.focus();
      showToast('⚠️ Inbox email is required');
      return;
    }
    setMsg('contact-email-msg', '✓ Leads will land here', 'ok');
    state.contactEmail = ce;
    try {
      const raw = localStorage.getItem(SESSION_KEY);
      if (raw) {
        const p = JSON.parse(raw);
        p.contactEmail = ce;
        p.smtpUser = (document.getElementById('smtp-user')?.value || '').trim();
        p.smtpPass = (document.getElementById('smtp-pass')?.value || '').replace(/\s+/g, '');
        localStorage.setItem(SESSION_KEY, JSON.stringify(p));
      }
    } catch (e) {}
    state.step = nextStep() || state.step;
    renderStep();
    return;
  }

  if (state.step === 3.5) {
    const u = state.adminUsername;
    const p = state.adminPassword;
    const p2 = document.getElementById('adm-pass2').value;
    const e = state.adminEmail;

    if (!/^[a-z][a-z0-9_]{3,19}$/.test(u)) { showToast('⚠️ Enter a valid username'); return; }
    if (p.length < 8) { showToast('⚠️ Password must be 8+ characters'); return; }
    if (p !== p2) { showToast('⚠️ Passwords do not match'); return; }
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(e)) { showToast('⚠️ Enter a valid recovery email'); return; }
    state.step = nextStep() || state.step;
    renderStep();
    return;
  }

  if (state.step === 3) {
    btn.disabled = true;
    // Contact inbox was collected (required) in Step 2 — final fallback to recovery email
    state.contactEmail = (state.contactEmail || state.adminEmail || '').trim();
    if (state.contactEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(state.contactEmail)) {
      showToast('⚠️ Contact inbox email looks invalid');
      btn.disabled = false;
      return;
    }
    if (window.Loader3D) Loader3D.show('Creating secure order…', 'Reserving your site + checkout', 'lock');
    const original = btn.innerHTML;
    btn.innerHTML = '⏳ Creating order…';
    try {
      const res = await fetch(SITE_URL + '/publish.php', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'create_order',
          siteName: state.siteName,
          genMode: state.genMode,
          conceptIndex: state.conceptIndex,
          package: state.package,
          adminUsername: state.adminUsername,
          adminPassword: state.adminPassword,
          adminEmail: state.adminEmail,
          contactEmail: state.contactEmail || state.adminEmail,
          smtpUser: state.smtpUser || '',
          smtpPass: state.smtpPass || '',
          useSubdomain: !!state.useSubdomain,
          html: state.html,
          draftToken: state.draftToken || '',  // ★ Server draft fallback
          adminFiles: JSON.stringify(state.adminFiles || {}),
          adminSql: state.adminSql || '',
          adminEntities: JSON.stringify(state.adminEntities || [])
        })
      });
      const j = await res.json();
      if (!j.success) {
        if (window.Loader3D) Loader3D.hide();
        showToast('❌ ' + ((j.errors || []).join(' · ') || 'Order failed'));
        btn.disabled = false; btn.innerHTML = original;
        return;
      }
      state.orderId = j.order_id;
      showToast('✓ Opening checkout…');
      setTimeout(() => { window.location.href = j.checkout_url; }, 500);
    } catch (err) {
      console.error(err);
      if (window.Loader3D) Loader3D.hide();
      showToast('❌ Network error');
      btn.disabled = false; btn.innerHTML = original;
    }
  }
}

