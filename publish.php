    { t: 'Writing PHP files…', m: 'Login, dashboard, CRUD pages', p: 55 },
    { t: 'Finalizing code…', m: 'Adding validation & styling', p: 80 },
    { t: 'Almost done…', m: 'Packaging files', p: 95 }
  ];
  let i = 0;
  const stageInterval = setInterval(() => {
    if (i < stages.length) {
