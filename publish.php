function detectStepFromUrl() {
  const params = new URLSearchParams(location.search);
  const oid = params.get('order_id');
  const step = params.get('step');
  if (step === 'done' && oid) {
    state.orderId = oid;
    finalizeOrder(oid);
  }
  if (params.get('payment_cancelled') === '1') {
    setTimeout(() => showToast('⚠️ Payment cancelled. You can try again below.'), 600);
    if (oid) {
      state.step = 3;
      renderStep();
    }
  }
  if (params.get('payment_error')) {
    setTimeout(() => showToast('❌ Payment error: ' + decodeURIComponent(params.get('payment_error'))), 600);
  }
}


function loadFromSession() {
  try {
    let raw = localStorage.getItem(SESSION_KEY);
    // Fallback: stale tab — scan sibling scoped keys for valid designs
    if (!raw) {
      for (let i = 0; i < localStorage.length; i++) {
        const k = localStorage.key(i);
        if (!k || k.indexOf('webcraft_saved_project::') !== 0 || k === SESSION_KEY) continue;
        const cand = localStorage.getItem(k);
        if (!cand) continue;
        try {
          const p = JSON.parse(cand);
          if (p && Array.isArray(p.designs) && p.designs.length > 0) { raw = cand; break; }
        } catch (e) {}
      }
    }
    if (!raw) return;
    const p = JSON.parse(raw);

    state.siteName    = p.bizName || 'My Website';
    state.conceptIndex = p.activeDesignIndex || 0;
    state.genMode     = p.selectedGenMode || 'static';
    state.hasAdmin    = state.genMode !== 'static';
    state.bizType     = p.wizard?.biz_type || 'business';
    state.adminRequirements = p.wizard?.admin_requirements || '';
    state.adminUsername = p.adminUsername || '';
    state.adminPassword = p.adminPassword || '';
    state.adminEmail    = p.adminEmail || p.wizard?.biz_email || '';
    state.contactEmail  = p.contactEmail || state.adminEmail;

    // Pre-populate credentials inputs if previously customized
    const uInp = document.getElementById('adm-user');
    const pInp = document.getElementById('adm-pass');
    const p2Inp = document.getElementById('adm-pass2');
    const eInp = document.getElementById('adm-email');
    if (uInp && state.adminUsername) {
      uInp.value = state.adminUsername;
      updateAdminUrlPreview();
    }
    if (pInp && state.adminPassword) {
      pInp.value = state.adminPassword;
      if (p2Inp) p2Inp.value = state.adminPassword;
      const s = scorePassword(state.adminPassword);
      const bar = document.getElementById('pw-bar');
      if (bar) bar.className = 'pw-strength-fill s' + s;
    }
    if (eInp && state.adminEmail) {
      eInp.value = state.adminEmail;
    }
    const cInp = document.getElementById('contact-email');
    if (cInp && state.contactEmail) {
      cInp.value = state.contactEmail;
    }
    state.smtpUser = p.smtpUser || '';
    state.smtpPass = p.smtpPass || '';
    const suInp = document.getElementById('smtp-user');
    if (suInp && state.smtpUser) suInp.value = state.smtpUser;
    const spInp = document.getElementById('smtp-pass');
    if (spInp && state.smtpPass) spInp.value = state.smtpPass;
    const flowPrev = document.getElementById('contact-flow-preview');
    if (flowPrev && state.contactEmail) {
      flowPrev.textContent = state.contactEmail;
    }

    const d = (p.designs || [])[state.conceptIndex] || {};
    state.html       = d.html || '';
    state.draftToken = p.draftToken || '';  // ★ Server-side draft fallback token

    // If html is too large or was stripped from localStorage, show notice
    if (!state.html && state.draftToken) {
      console.log('📡 Design will be loaded from server draft:', state.draftToken);
    }

    // Hide admin steps if not needed
    if (!state.hasAdmin) {
      document.getElementById('step-btn-2')?.classList.add('hidden');
      document.getElementById('step-btn-35')?.classList.add('hidden');
    }

    updateReview();
    if (typeof updatePubAddrUI === 'function') updatePubAddrUI();
  } catch (e) { console.warn('loadFromSession:', e); }
}

