// ─── Utilities ──────────────────────────────────────────
function clean(string $v): string { return htmlspecialchars(strip_tags(trim($v)), ENT_QUOTES, 'UTF-8'); }
function slugify(string $s): string { $s = strtolower(trim($s)); $s = preg_replace('/[^a-z0-9]+/', '-', $s); return trim($s, '-') ?: 'site'; }
function ordersDir(): string { $d = defined('STORAGE_DIR') ? STORAGE_DIR . '/orders' : __DIR__ . '/storage/orders'; if (!is_dir($d)) @mkdir($d, 0755, true); return $d; }
function publishedDir(): string { $d = __DIR__ . '/published'; if (!is_dir($d)) @mkdir($d, 0755, true); return $d; }
function loadOrder(string $orderId): ?array {
    $f = ordersDir() . '/' . $orderId . '.json';
    if (!file_exists($f)) return null;
    return json_decode(file_get_contents($f), true);
}
function saveOrder(array $o): bool {
    return file_put_contents(ordersDir() . '/' . $o['order_id'] . '.json', json_encode($o, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE)) !== false;
}

/**
 * Inject real contact-form AJAX wiring into published HTML.
 * Only hijacks forms that look like contact forms (email + message field);
 * newsletter-only forms are left for the site's own script.
 */
function injectContactHandler(string $html): string {
    $js = <<<'WCJS'
<script>
/* WebCraft contact wiring — sends this form to contact.php via platform mailer */
(function(){
  function note(msg, ok){
    var d = document.createElement('div');
    d.textContent = msg;
    d.style.cssText = 'position:fixed;bottom:24px;left:50%;transform:translateX(-50%);z-index:99999;padding:12px 22px;border-radius:10px;font-weight:700;font-size:14px;font-family:inherit;box-shadow:0 10px 30px rgba(0,0,0,.4);background:' + (ok ? '#059669' : '#dc2626') + ';color:#fff;';
    document.body.appendChild(d);
    setTimeout(function(){ d.remove(); }, 4000);
  }
  document.addEventListener('submit', function(e){
    var f = e.target;
    if (!f || f.tagName !== 'FORM' || f.dataset.wcWired) return;
    var hasEmail = f.querySelector('input[type=email]');
    var hasMsg = f.querySelector('textarea') || f.querySelector('[name=message],[name=your-message],[name=comments]') || f.id === 'contact-form';
    if (!hasEmail || !hasMsg) return; // not a contact form — leave it alone
    e.preventDefault();
    e.stopImmediatePropagation();
    f.dataset.wcWired = '1';
    var btn = f.querySelector('[type=submit],button');
    var orig = btn ? btn.innerHTML : '';
    if (btn) { btn.disabled = true; btn.innerHTML = 'Sending…'; }
    fetch('contact.php', { method: 'POST', body: new FormData(f) })
      .then(function(r){ return r.json(); })
      .then(function(j){
        if (j && j.success) {
          f.innerHTML = '<div style="padding:28px;text-align:center;background:rgba(16,185,129,.1);border:1.5px solid #10b981;border-radius:12px;font-weight:700;">✓ Thank you! Your message has been sent. We will reply soon.</div>';
        } else {
          note((j && j.error) || 'Could not send. Try again.', false);
          if (btn) { btn.disabled = false; btn.innerHTML = orig; }
          delete f.dataset.wcWired;
        }
      })
      .catch(function(){
        note('Network error. Try again.', false);
        if (btn) { btn.disabled = false; btn.innerHTML = orig; }
        delete f.dataset.wcWired;
      });
  }, true);
})();
</script>
WCJS;
    if (stripos($html, '</body>') !== false) {
        return preg_replace('/<\/body\s*>/i', $js . "\n</body>", $html, 1);
    }
    return $html . "\n" . $js;
}

/**
 * Build contact.php receiver: validates + rate-limits + sends via OWNER Gmail
 * SMTP first (tested step-by-step at publish), platform queue as fallback.
 */
function buildContactReceiver(string $siteName, string $toEmail, string $smtpUser = '', string $smtpPass = ''): string {
    $siteSafe = addslashes($siteName);
    $toSafe = addslashes($toEmail);
    $smtpUserSafe = addslashes($smtpUser);
    $smtpPassSafe = addslashes($smtpPass);
    return <<<"WCPHP"
<?php
// contact.php — Contact form receiver for "{$siteSafe}". Auto-generated by WebCraft AI.
header('Content-Type: application/json');
header('X-Content-Type-Options: nosniff');

define('OWNER_SMTP_USER', '{$smtpUserSafe}');
define('OWNER_SMTP_PASS', '{$smtpPassSafe}');

if (\$_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['success' => false, 'error' => 'Method not allowed']);
    exit;
}

// Honeypot (bots fill it, humans don't)
if (!empty(\$_POST['company'])) { echo json_encode(['success' => true]); exit; }

function pick(\$keys) {
    foreach (\$keys as \$k) {
        if (!empty(\$_POST[\$k]) && is_string(\$_POST[\$k])) return trim(\$_POST[\$k]);
    }
    return '';
}
\$name    = strip_tags(pick(['name', 'your-name', 'full-name', 'fullname']));
\$email   = trim(pick(['email', 'your-email', 'email-address']));
\$phone   = strip_tags(pick(['phone', 'your-phone', 'tel', 'mobile']));
\$message = strip_tags(pick(['message', 'your-message', 'comments', 'comment', 'enquiry']));

if (\$name === '' || \$message === '' || !filter_var(\$email, FILTER_VALIDATE_EMAIL)) {
    http_response_code(400);
    echo json_encode(['success' => false, 'error' => 'Please fill your name, a valid email and your message.']);
    exit;
}
if (strlen(\$message) > 5000) \$message = substr(\$message, 0, 5000);

// Basic per-IP throttle: 20/hour
\$ip = \$_SERVER['REMOTE_ADDR'] ?? 'unknown';
\$hitsFile = __DIR__ . '/contact_hits.json';
\$hits = file_exists(\$hitsFile) ? (json_decode(@file_get_contents(\$hitsFile), true) ?: []) : [];
\$now = time();
\$hits = array_values(array_filter(\$hits, function (\$h) use (\$now, \$ip) {
    return is_array(\$h) && (\$now - (\$h['t'] ?? 0)) < 3600 && (\$h['ip'] ?? '') === \$ip;
}));
if (count(\$hits) >= 20) {
    http_response_code(429);
    echo json_encode(['success' => false, 'error' => 'Too many messages. Please try again later.']);
    exit;
}
\$hits[] = ['ip' => \$ip, 't' => \$now];
@file_put_contents(\$hitsFile, json_encode(\$hits));

// Save to owner admin inbox (Admin → Inbox page lists these)
\$inboxDir = __DIR__ . '/admin';
if (is_dir(\$inboxDir)) {
    \$inboxFile = \$inboxDir . '/data_inquiries.json';
    \$inbox = file_exists(\$inboxFile) ? (json_decode(@file_get_contents(\$inboxFile), true) ?: []) : [];
    if (!is_array(\$inbox)) \$inbox = [];
    array_unshift(\$inbox, [
        'id' => (string)(time() . rand(100, 999)),
        'name' => \$name, 'email' => \$email, 'phone' => \$phone,
        'message' => \$message, 'date' => date('Y-m-d H:i'), 'read' => false,
    ]);
    \$inbox = array_slice(\$inbox, 0, 500);
    @file_put_contents(\$inboxFile, json_encode(\$inbox, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
}

require dirname(dirname(__DIR__)) . '/includes/MailQueue.php';

\$subject = 'New website enquiry — {$siteSafe}';
\$bodyHtml = '<div style="font-family:Segoe UI,Arial,sans-serif;color:#111;padding:20px;">'
    . '<h2 style="margin:0 0 12px;">New enquiry from your website</h2>'
    . '<p><strong>Name:</strong> ' . htmlspecialchars(\$name) . '<br>'
    . '<strong>Email:</strong> ' . htmlspecialchars(\$email) . '<br>'
    . '<strong>Phone:</strong> ' . htmlspecialchars(\$phone ?: '—') . '</p>'
    . '<div style="background:#f3f4f6;border-radius:10px;padding:14px;white-space:pre-wrap;">' . htmlspecialchars(\$message) . '</div>'
    . '<p style="color:#6b7280;font-size:12px;">Reply directly to ' . htmlspecialchars(\$email) . '.</p></div>';
\$bodyText = "Name: {\$name}\nEmail: {\$email}\nPhone: {\$phone}\n\n{\$message}";

// 1) Owner Gmail SMTP first (their own address sends it, Reply-To = visitor)
if (OWNER_SMTP_USER !== '' && OWNER_SMTP_PASS !== '') {
    try {
        \$m = Mailer::getInstance();
        \$m->Username = OWNER_SMTP_USER;
        \$m->Password = OWNER_SMTP_PASS;
        \$m->setFrom(OWNER_SMTP_USER, '{$siteSafe} Website');
        \$m->clearAllRecipients();
        \$m->addAddress('{$toSafe}');
        \$m->addReplyTo(\$email, \$name);
        \$m->isHTML(true);
        \$m->Subject = \$subject;
        \$m->Body = \$bodyHtml;
        \$m->AltBody = \$bodyText;
        \$m->send();
        echo json_encode(['success' => true, 'via' => 'owner_gmail']);
        exit;
    } catch (Throwable \$e) {
        // fall through to platform queue below
    }
}

// 2) Platform queue fallback — instant response, delivery retries automatically
\$res = queueMail(['to' => '{$toSafe}', 'subject' => \$subject, 'html' => \$bodyHtml,
    'text' => \$bodyText, 'kind' => 'contact']);
if (!empty(\$res['success'])) {
    echo json_encode(['success' => true]);
} else {
    http_response_code(500);
    echo json_encode(['success' => false, 'error' => 'Mail server busy. Please try again later.']);
}
WCPHP;
}

