<?php
// includes/SiteApiBridge.php — Per-site API bridge writer.
//
// Published sites live at /published/<slug>/, but the storefront runtime
// calls a RELATIVE "api/business-ops.php". Without this bridge that URL
// 404s (published/<slug>/api/… does not exist) and — with Node down —
// every booking/search/history call dies ("service temporarily
// unavailable"). The bridge forwards to the real root endpoint.
if (!function_exists('writeSiteApiBridge')) {
    function writeSiteApiBridge(string $targetDir): bool {
        $apiDir = rtrim($targetDir, '/\\') . '/api';
        if (!is_dir($apiDir)) @mkdir($apiDir, 0755, true);
        if (!is_dir($apiDir)) return false;
        $code = <<<'PHP'
<?php
// Auto-generated by WebCraft AI at publish time. Same-directory bridge so
// storefront JS (relative "api/business-ops.php") always reaches the real
// backend. Slug travels in the JSON body; nothing is stored here.
require dirname(__DIR__, 3) . '/api/business-ops.php';
PHP;
        return @file_put_contents($apiDir . '/business-ops.php', $code, LOCK_EX) !== false;
    }
}
