function preview_id_valid(string $id): bool {
    return (bool)preg_match('/^[a-f0-9]{32}$/', $id);
}

function preview_dir(string $id): string {
    return preview_root() . '/' . $id;
}

function preview_draft_meta(string $id): array {
    $f = preview_dir($id) . '/draft.json';
    if (!preview_id_valid($id) || !is_file($f)) return [];
    $j = json_decode(@file_get_contents($f), true);
    return is_array($j) ? $j : [];
}

/** Cap stored preview envs (oldest by mtime go first). Data persists —
 *  nothing expires by age; reopening a draft reuses its env. */
function preview_gc(int $keep = 30): void {
    $root = preview_root();
    $dirs = [];
    foreach (glob($root . '/*', GLOB_ONLYDIR) ?: [] as $d) {
        if (!preg_match('#/([a-f0-9]{32})$#', $d)) continue;
        $dirs[] = $d;
    }
    if (count($dirs) <= $keep) return;
    usort($dirs, fn($a, $b) => filemtime($a) - filemtime($b));
    foreach (array_slice($dirs, 0, count($dirs) - $keep) as $old) {
        preview_rrmdir($old);
    }
}

function preview_rrmdir(string $d): void {
    // Safety: never delete filesystem roots, the preview root itself, or
    // anything outside it — even if called with a bad/empty id.
    $d = rtrim($d, '/\\');
    $root = rtrim(preview_root(), '/\\');
    if ($d === '' || strlen($d) < strlen($root) + 2) return;
    if (strncasecmp($d, $root, strlen($root)) !== 0) return;
    if (!is_dir($d)) return;
    foreach (scandir($d) ?: [] as $f) {
        if ($f === '.' || $f === '..') continue;
        $p = $d . '/' . $f;
        is_dir($p) ? preview_rrmdir($p) : @unlink($p);
    }
    @rmdir($d);
}

function preview_valid_username(string $u): string {
    $u = strtolower(trim($u));
    return preg_match('/^[a-z][a-z0-9_]{3,19}$/', $u) ? $u : 'admin';
}

/** Entities whose rows are customer submissions — never auto-copied to prod. */
function preview_is_transactional(string $entityId): bool {
    $e = strtolower($entityId);
    foreach (['booking', 'order', 'inquir', 'message', 'ticket', 'payment',
              'appoint', 'reserv', 'subscrib', 'customer', 'client', 'member',
              'review', 'quot', 'lead', 'comment', 'feedback', 'cancel',
              'refund', 'invoice', 'transaction'] as $kw) {
        if (strpos($e, $kw) !== false) return true;
    }
    return false;
}

