function preview_root(): string {
    $d = dirname(__DIR__) . '/preview';
    if (!is_dir($d)) @mkdir($d, 0755, true);
    // Never serve dotfiles, raw JSON tables, or installer markers.
    $ht = $d . '/.htaccess';
    if (!is_file($ht)) {
        @file_put_contents($ht, "<FilesMatch \"(^\\.|\\.json\$|\\.installed\$|\\.attempts\\.json\$|_hits\\.json\$)\">\n"
            . "  Require all denied\n</FilesMatch>\n");
    }
    return $d;
}

/**
 * Per-env access gate files. All requests route through gate.php, which
 * enforces sharing/expiry, denies private files, serves static assets, and
 * executes local PHP in place. The FilesMatch layer keeps private files
 * denied even where mod_rewrite is unavailable.
 */
function preview_gate_files(string $dir): void {
    $htaccess = <<<'HTA'
RewriteEngine On
RewriteCond %{ENV:REDIRECT_STATUS} ^$
RewriteRule ^(.*)$ gate.php?__gate=$1 [QSA,L]
<FilesMatch "(^\.|\.json$|\.installed$|\.attempts\.json$|_hits\.json$)">
  Require all denied
</FilesMatch>
HTA;
    @file_put_contents(rtrim($dir, '/') . '/.htaccess', $htaccess, LOCK_EX);
    @file_put_contents(rtrim($dir, '/') . '/gate.php', preview_gate_php(), LOCK_EX);
}

