/**
 * Provision (or refresh) a preview env. Code files are rewritten; preview
 * records, credentials (unless rotated), and settings are always preserved.
 * Returns ['ok'=>bool, 'env'=>[...] | 'error'=>...].
 */
function preview_provision(array $p): array {
    $token = strtolower(trim((string)($p['draftToken'] ?? '')));
    if (!preview_id_valid($token)) $token = bin2hex(random_bytes(16));
    $root = preview_root();
    preview_gc();
    $dir = $root . '/' . $token;
    $adminDir = $dir . '/admin';
    if (!is_dir($adminDir) && !@mkdir($adminDir, 0755, true)) {
        return ['ok' => false, 'error' => 'Cannot create preview directory.'];
    }

    $html = (string)($p['html'] ?? '');
    if (strlen($html) < 100) return ['ok' => false, 'error' => 'Empty design HTML.'];
    if (strlen($html) > 7 * 1024 * 1024) return ['ok' => false, 'error' => 'Design HTML too large.'];

    $bizName = substr(trim((string)($p['bizName'] ?? 'Preview Website')) ?: 'Preview Website', 0, 120);
    $slug = preg_replace('/[^a-z0-9\-]/i', '', (string)($p['slug'] ?? '')) ?: pak_slug($bizName);
    $contactEmail = filter_var(trim((string)($p['contactEmail'] ?? '')), FILTER_VALIDATE_EMAIL) ?: '';
    $entities = pak_normalize_entities((array)($p['entities'] ?? []));
    if (empty($entities)) $entities = pak_default_entities();

    // Draft meta (entities evolve via add_feature; everything else stable).
    $metaFile = $dir . '/draft.json';
    $meta = is_file($metaFile) ? (json_decode(@file_get_contents($metaFile), true) ?: []) : [];
    if (!is_array($meta)) $meta = [];
    // Union with previously added features: a rebuild from the current
    // design must never drop entities installed via add_feature (they are
    // the tested functionality that publish must ship). Fresh spec wins
    // on id conflicts; previously added extras are preserved.
    $prevEnts = [];
    foreach ((array)($meta['entities'] ?? []) as $pe) {
        if (is_array($pe) && !empty($pe['id'])) $prevEnts[(string)$pe['id']] = $pe;
    }
    foreach ($entities as $e) $prevEnts[$e['id']] = [
        'id' => $e['id'], 'name' => $e['name'], 'singular' => $e['singular'],
        'icon' => $e['icon'], 'fields' => $e['fields']];
    $mergedEnts = array_values($prevEnts);
    $entities = pak_normalize_entities($mergedEnts);
    $meta['token'] = $token;
    $meta['bizName'] = $bizName;
    $meta['slug'] = substr($slug, 0, 60);
    $meta['entities'] = array_map(fn($e) => ['id' => $e['id'], 'name' => $e['name'],
        'singular' => $e['singular'], 'icon' => $e['icon'], 'fields' => $e['fields']], $entities);
    $meta['contactEmail'] = $contactEmail;
    $meta['genMode'] = in_array(($p['genMode'] ?? ''), ['static', 'admin', 'database'], true) ? $p['genMode'] : 'admin';
    $meta['createdAt'] = $meta['createdAt'] ?? date('c');
    $meta['updatedAt'] = date('c');
    $meta['htmlHash'] = md5($html);

    // Credentials: explicit valid pair wins; stored hash kept when the
    // provided password still verifies (no surprise rotation); otherwise a
    // one-time generated password is returned (never stored plaintext).
    $authFile = $adminDir . '/.auth.json';
    $auth = is_file($authFile) ? (json_decode(@file_get_contents($authFile), true) ?: []) : [];
    if (!is_array($auth)) $auth = [];
    $adminUser = preview_valid_username((string)($p['adminUser'] ?? $auth['username'] ?? 'admin'));
    $providedPass = (string)($p['adminPass'] ?? '');
    $storedHash = (string)($auth['hash'] ?? '');
    $hashOk = ($storedHash !== '' && (str_starts_with($storedHash, '$2y$') || str_starts_with($storedHash, '$argon2')));
    $generatedPass = null;
    if ($providedPass !== '' && strlen($providedPass) >= 8) {
        if (!($hashOk && password_verify($providedPass, $storedHash))) {
            $storedHash = password_hash($providedPass, PASSWORD_DEFAULT);
            $hashOk = true;
        }
    }
    if (!$hashOk) {
        $generatedPass = substr(bin2hex(random_bytes(9)), 0, 12);
        $storedHash = password_hash($generatedPass, PASSWORD_DEFAULT);
    }
    $auth['username'] = $adminUser;
    if ($contactEmail !== '') $auth['email'] = $contactEmail;
    elseif (empty($auth['email'])) $auth['email'] = '';
    $auth['hash'] = $storedHash;
    unset($auth['password_plain'], $auth['password']);
    $auth['order_id'] = $auth['order_id'] ?? '';
    $auth['preview'] = true;
    $auth['updated_at'] = date('Y-m-d H:i:s');
    if (@file_put_contents($authFile, json_encode($auth, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE), LOCK_EX) === false) {
        return ['ok' => false, 'error' => 'Cannot write preview credentials.'];
    }

    // Keep the server-side draft HTML in sync (publish fallback reads it).
    $draftsDir = (defined('STORAGE_DIR') ? STORAGE_DIR : dirname(__DIR__) . '/storage') . '/drafts';
    if (!is_dir($draftsDir)) @mkdir($draftsDir, 0755, true);
    @file_put_contents($draftsDir . '/' . $token . '.html', $html);
    @file_put_contents($draftsDir . '/' . $token . '.json', json_encode([
        'token' => $token, 'biz_name' => $bizName, 'preview' => true,
        'saved_at' => date('Y-m-d H:i:s')], JSON_PRETTY_PRINT));

    // Site HTML: contact wiring + universal form wiring, then the REAL
    // backend runtime LAST. Keep the runtime as the final <script> before
    // </body>: any later tail injector can otherwise land inside its JS and
    // terminate it, which silently leaves an AI-generated mock in control
    // (fake BK- references, no backend writes).
    require_once __DIR__ . '/BusinessRuntime.php';
    $spec = is_array($p['bizSpec'] ?? null) ? $p['bizSpec'] : ['entities' => $meta['entities']];
    if ($contactEmail !== '' && stripos($html, '<form') !== false) $html = injectContactHandler($html);
    $html = pak_wire_frontend_forms($html, pak_form_entity_map($entities));
    $html = business_runtime_inject($html, $spec, $token);
    if (pak_write($dir . '/index.html', $html) === false) {
        return ['ok' => false, 'error' => 'Cannot write preview site.'];
    }
    if (wc_business_requires_bus_booking($spec)
        && !copy(dirname(__DIR__) . '/includes/templates/bus-customer-portal.php', $dir . '/customer.php')) {
        return ['ok' => false, 'error' => 'Cannot create preview customer booking portal.'];
    }
    if (wc_business_requires_bus_booking($spec)) {
        @copy(dirname(__DIR__) . '/includes/templates/bus-ticket-verify.php', $dir . '/verify.php');
    }

    // Public handlers in the preview root (isolated from production).
    if ($contactEmail !== '') {
        pak_write($dir . '/contact.php', buildContactReceiver($bizName, $contactEmail, $slug));
    }
    $orderlike = preview_orderlike($meta, $entities, $adminUser, $storedHash);
    pak_public_handlers($dir, $orderlike, $entities);
    if (function_exists('writeSiteApiBridge')) writeSiteApiBridge($dir);
    // Access gate (share controls, private-file denial, static + PHP router).
    preview_gate_files($dir);
    // Sharing: unguessable URL is shareable; links live 14 days, extended by
    // each rebuild while enabled — revocation is never undone implicitly.
    if (!isset($meta['sharing']) || !is_array($meta['sharing'])) {
        $meta['sharing'] = ['enabled' => true, 'expiresAt' => time() + 14 * 86400];
    } elseif (!empty($meta['sharing']['enabled'])) {
        $meta['sharing']['expiresAt'] = max((int)($meta['sharing']['expiresAt'] ?? 0), time() + 14 * 86400);
    }

    // Full admin: base install first (login/logout/layout), required kit on
    // top (helpers, entity pages, inbox, settings, api, installer). Both are
    // additive — preview records and credentials are never reset.
    require_once __DIR__ . '/AdminPanelGenerator.php';
    try {
        AdminPanelGenerator::install($adminDir, $orderlike);
    } catch (Throwable $e) {
        return ['ok' => false, 'error' => 'Admin install failed: ' . substr($e->getMessage(), 0, 160)];
    }
    $pakRes = pak_install($adminDir, $orderlike);
    if (!empty($pakRes['errors'])) {
        error_log('[preview provision] ' . implode('; ', $pakRes['errors']));
    }
    // ★ Demo schedules live in the backend too: seed trips when the concept
    // exists but the store is empty, so the storefront lists them via the
    // normal API (never hardcoded-only, never an empty page).
    try {
        require_once __DIR__ . '/BusinessOps.php';
        if (function_exists('bops_seed_demo_trips')) {
            bops_seed_demo_trips($token, $adminDir, array_column($entities, 'id'));
        }
    } catch (Throwable $e) { error_log('[preview seed] ' . $e->getMessage()); }
    // Mark installed (installer stays honest: refuses repeat runs).
    @file_put_contents($adminDir . '/.installed', json_encode(['installed_at' => date('c'), 'preview' => true]), LOCK_EX);

    pak_write($metaFile, json_encode($meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

    $base = defined('SITE_URL') ? rtrim(SITE_URL, '/') : '';
    $env = [
        'id' => $token,
        'siteUrl' => $base . '/preview/' . $token . '/',
        'adminUrl' => $base . '/preview/' . $token . '/admin/login.php',
        'adminUser' => $adminUser,
        'entities' => array_column($entities, 'id'),
    ];
    if ($generatedPass !== null) $env['adminPassOnce'] = $generatedPass;
    return ['ok' => true, 'env' => $env];
}

/**
 * Apply an AI-generated feature to a preview env (validates, merges without
 * duplicates, creates data files + CRUD pages, refreshes nav, preserves
 * records). Mirrors site-manager's add_feature contract.
 */
function preview_add_feature(string $id, array $files, array $entities, string $requirements = ''): array {
    if (!preview_id_valid($id) || !is_dir(preview_dir($id) . '/admin')) {
        return ['ok' => false, 'error' => 'Preview env not found. Provision it first.'];
    }
    $adminDir = preview_dir($id) . '/admin';
    $meta = preview_draft_meta($id);
    $filesAdded = 0;
    $errors = [];

    $validEntities = pak_normalize_entities(array_values($entities));
    if (!empty($entities) && empty($validEntities)) {
        $errors[] = 'New entity definitions were invalid and were skipped.';
    }

    foreach ($files as $relPath => $content) {
        $safe = pak_safe_relpath((string)$relPath);
        if ($safe === null || $safe === '') { $errors[] = (string)$relPath . ' (blocked unsafe path)'; continue; }
        if (!is_string($content)) { $errors[] = $safe . ' (invalid content)'; continue; }
        $full = $adminDir . '/' . $safe;
        $d = dirname($full);
        if (!is_dir($d)) @mkdir($d, 0755, true);
        if (@file_put_contents($full, $content, LOCK_EX) !== false) $filesAdded++;
        else $errors[] = $safe . ' (write failed)';
    }

    // Merge entities into draft meta + admin manifest (dedupe by id).
    $have = [];
    foreach ((array)($meta['entities'] ?? []) as $e) {
        if (is_array($e) && !empty($e['id'])) $have[(string)$e['id']] = true;
    }
    $added = [];
    foreach ($validEntities as $ent) {
        if (!isset($have[$ent['id']])) {
            $meta['entities'][] = ['id' => $ent['id'], 'name' => $ent['name'],
                'singular' => $ent['singular'], 'icon' => $ent['icon'], 'fields' => $ent['fields']];
            $have[$ent['id']] = true;
            $added[] = $ent['id'];
        }
    }
    $meta['updatedAt'] = date('c');
    if (!isset($meta['feature_additions']) || !is_array($meta['feature_additions'])) $meta['feature_additions'] = [];
    $meta['feature_additions'][] = ['requirements' => substr($requirements, 0, 2000),
        'files_added' => $filesAdded, 'entities_added' => $added, 'added_at' => date('Y-m-d H:i:s')];
    pak_write(preview_dir($id) . '/draft.json', json_encode($meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

    if (!empty($added)) {
        $mf = $adminDir . '/manifest.json';
        if (is_file($mf)) {
            $m = json_decode(@file_get_contents($mf), true);
            if (is_array($m)) {
                if (!isset($m['entities']) || !is_array($m['entities'])) $m['entities'] = [];
                $mIds = [];
                foreach ($m['entities'] as $me) { if (is_array($me) && !empty($me['id'])) $mIds[(string)$me['id']] = true; }
                foreach ($validEntities as $ent) {
                    if (!isset($mIds[$ent['id']])) {
                        $m['entities'][] = ['id' => $ent['id'], 'name' => $ent['name'],
                            'singular' => $ent['singular'], 'icon' => $ent['icon'], 'fields' => $ent['fields']];
                    }
                }
                $m['updated_at'] = date('c');
                @file_put_contents($mf, json_encode($m, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE), LOCK_EX);
            }
        }
        $orderlike = preview_orderlike($meta, pak_normalize_entities((array)$meta['entities']),
            (string)($meta['adminUser'] ?? preview_valid_username('admin')), 'x');
        // pak_install only refreshes code + inits missing data files.
        $pakRes = pak_install($adminDir, $orderlike);
        foreach ((array)($pakRes['errors'] ?? []) as $e) $errors[] = $e;
        preview_refresh_nav($adminDir, pak_normalize_entities((array)$meta['entities']));
    }

    return ['ok' => true, 'files_added' => $filesAdded, 'entities_added' => $added,
        'errors' => $errors, 'adminUrl' => (defined('SITE_URL') ? rtrim(SITE_URL, '/') : '') . '/preview/' . $id . '/admin/login.php'];
}

/** Refresh generated layout/manage nav payloads (generated files carry no
 *  user data, so refreshing them is safe). Shared with site-manager. */
function preview_refresh_nav(string $adminDir, array $entities): void {
    try {
        $payload = json_encode($entities, JSON_UNESCAPED_UNICODE);
        if (!is_string($payload) || $payload === '') return;
        $embed = str_replace(['\\', "'"], ['\\\\', "\\'"], $payload);
        foreach (['layout.php', 'manage.php'] as $genFile) {
            $gf = rtrim($adminDir, '/') . '/' . $genFile;
            if (!is_file($gf)) continue;
            $gc = @file_get_contents($gf);
            if (!is_string($gc) || $gc === '') continue;
            $gc2 = preg_replace("/json_decode\\('.*?', true\\) \\?: \\[\\]/s",
                "json_decode('" . $embed . "', true) ?: []", $gc, 1);
            if (is_string($gc2) && $gc2 !== $gc) @file_put_contents($gf, $gc2, LOCK_EX);
        }
    } catch (Throwable $e) { error_log('[preview nav refresh] ' . $e->getMessage()); }
}

/**
 * Readiness report: real checks against the provisioned env (files, manifest,
 * auth, storage, form→handler mapping, mock-string scan). Nothing auto-passes.
 */
function preview_readiness(string $id): array {
    $checks = [];
    $add = function (string $key, string $label, bool $pass, bool $critical, string $detail = '') use (&$checks) {
        $checks[] = ['key' => $key, 'label' => $label, 'pass' => $pass, 'critical' => $critical, 'detail' => $detail];
    };
    if (!preview_id_valid($id) || !is_dir(preview_dir($id))) {
        $add('env', 'Preview env exists', false, true, 'Provision the preview first.');
        return ['ok' => true, 'ready' => false, 'checks' => $checks];
    }
    $dir = preview_dir($id);
    $adminDir = $dir . '/admin';
    $meta = preview_draft_meta($id);
    $add('env', 'Preview env exists', true, true, $id);

    $idx = is_file($dir . '/index.html') ? (string)@file_get_contents($dir . '/index.html') : '';
    $add('site', 'Site HTML generated', strlen($idx) > 100, true, strlen($idx) . ' bytes');

    $entities = array_values(array_filter(array_map(fn($e) => is_array($e) ? (string)($e['id'] ?? '') : '', (array)($meta['entities'] ?? []))));
    $add('manifest', 'Manifest has entities', !empty($entities), true, implode(', ', $entities));

    $auth = is_file($adminDir . '/.auth.json') ? (json_decode(@file_get_contents($adminDir . '/.auth.json'), true) ?: []) : [];
    $hash = (string)($auth['hash'] ?? '');
    $add('auth', 'Admin credentials (hash-only)', $hash !== '' && (str_starts_with($hash, '$2y$') || str_starts_with($hash, '$argon2'))
        && strpos(json_encode($auth), 'password_plain') === false, true, 'user: ' . ($auth['username'] ?? '?'));

    $required = ['includes/auth.php', 'includes/db.php', 'includes/layout.php', 'index.php',
        'inbox.php', 'settings.php', 'api.php', 'install.php', 'login.php'];
    $missing = [];
    foreach ($required as $rel) { if (!is_file($adminDir . '/' . $rel)) $missing[] = $rel; }
    foreach ($entities as $eid) { if (!is_file($adminDir . '/' . $eid . '.php')) $missing[] = $eid . '.php'; }
    $add('pages', 'Admin pages generated', empty($missing), true, empty($missing) ? (count($entities) . ' entities') : ('missing: ' . implode(', ', $missing)));

    $badData = [];
    $counts = [];
    foreach ($entities as $eid) {
        $f = $adminDir . '/data_' . $eid . '.json';
        if (!is_file($f)) { $badData[] = $eid . ' (no file)'; continue; }
        $j = json_decode(@file_get_contents($f), true);
        if (!is_array($j)) { $badData[] = $eid . ' (invalid JSON)'; continue; }
        $counts[$eid] = count($j);
    }
    if (!is_file($adminDir . '/data_inquiries.json')) {
        @file_put_contents($adminDir . '/data_inquiries.json', '[]', LOCK_EX);
    }
    $add('data', 'JSON tables valid + writable', empty($badData) && is_writable($adminDir), true,
        empty($badData) ? json_encode($counts) : implode('; ', $badData));

    // Form → handler mapping: every data form must reach a real endpoint.
    $formIssues = [];
    $formCount = 0;
    if ($idx !== '' && preg_match_all('#<form\b[^>]*>#i', $idx, $fm)) {
        foreach ($fm[0] as $tag) {
            $formCount++;
            $isSearch = stripos($tag, 'data-wc-search') !== false;
            $isRemoteOff = stripos($tag, 'data-remote="off"') !== false;
            $hasWcForm = stripos($tag, 'data-wc-form') !== false;
            if ($isSearch) {
                if (!is_file($dir . '/api/business-ops.php')) $formIssues[] = 'search form without api bridge';
            } elseif ($isRemoteOff) {
                // Custom JS-driven (booking flows call WCBiz directly) — runtime present?
                if (stripos($idx, 'WCBiz') === false) $formIssues[] = 'custom form without runtime';
            } elseif ($hasWcForm || stripos($tag, 'contact-form') !== false || preg_match('#type=.email.#i', $tag)) {
                if (!is_file($dir . '/submit.php') && !is_file($dir . '/contact.php')) {
                    $formIssues[] = 'data form without submit.php/contact.php';
                }
            }
        }
    }
    $add('forms', 'Frontend forms wired to backend', empty($formIssues), true,
        $formCount . ' form(s)' . (empty($formIssues) ? '' : ': ' . implode('; ', array_unique($formIssues))));

    // Mock scan: generated admin must contain no fake-data markers. Only
    // RENDERED-row markers count (seed-generator code paths are dead when
    // tables seed empty, which preview/production always do).
    $mockHits = [];
    foreach (glob($adminDir . '/*.php') ?: [] as $pf) {
        $c = (string)@file_get_contents($pf);
        foreach (['Live after publish', 'generated on Publish', 'Sample Trip record',
                  'Sample Booking record', 'Sample Payment record', 'Sample Bu record',
                  'Sample Ticket record', 'Sample Record'] as $mk) {
            if (stripos($c, $mk) !== false) { $mockHits[] = basename($pf) . ':' . $mk; break; }
        }
    }
    $add('nomock', 'No mock placeholders in admin', empty($mockHits), false, empty($mockHits) ? 'clean' : implode('; ', $mockHits));

    // Storage: collections writable (isolated preview slug).
    $colDir = (defined('STORAGE_DIR') ? STORAGE_DIR : dirname(__DIR__) . '/storage') . '/collections/' . $id;
    if (!is_dir($colDir)) @mkdir($colDir, 0755, true);
    $add('storage', 'Isolated JSON storage writable', is_dir($colDir) && is_writable($colDir), true, 'collections/' . $id);

    // Sharing gate: files present, link live, private files denied over HTTP.
    $add('gate', 'Share gate installed', is_file($dir . '/gate.php') && is_file($dir . '/.htaccess'), true, 'gate.php + .htaccess');
    $sharing = is_array($meta['sharing'] ?? null) ? $meta['sharing'] : [];
    $shareLive = !empty($sharing['enabled']) && ((int)($sharing['expiresAt'] ?? 0) === 0 || time() <= (int)$sharing['expiresAt']);
    $add('sharing', 'Share link live', $shareLive, false,
        $shareLive ? ('expires ' . date('Y-m-d', (int)($sharing['expiresAt'] ?? time()))) : 'revoked or expired — re-share from the builder');
    $privProbe = preview_probe_private($id);
    $add('privacy', 'Private files denied over HTTP', $privProbe['pass'], $privProbe['verified'],
        $privProbe['detail']);

    $ready = true;
    foreach ($checks as $c) { if ($c['critical'] && !$c['pass']) { $ready = false; break; } }
    return ['ok' => true, 'ready' => $ready, 'checks' => $checks];
}

/**
 * Share controls: explicit expiry extension / revocation for a preview env.
 * Revocation (410) keeps all data — the owner can re-share anytime.
 */
function preview_share(string $id, int $days = 14): array {
    if (!preview_id_valid($id) || !is_dir(preview_dir($id))) {
        return ['ok' => false, 'error' => 'Preview not found.'];
    }
    if ($days < 1) $days = 1;
    if ($days > 90) $days = 90;
    $meta = preview_draft_meta($id);
    $meta['sharing'] = ['enabled' => true, 'expiresAt' => time() + $days * 86400];
    $meta['updatedAt'] = date('c');
    pak_write(preview_dir($id) . '/draft.json', json_encode($meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
    $base = defined('SITE_URL') ? rtrim(SITE_URL, '/') : '';
    return ['ok' => true, 'shareUrl' => $base . '/preview/' . $id . '/',
        'expiresAt' => date('c', $meta['sharing']['expiresAt'])];
}

function preview_revoke(string $id): array {
    if (!preview_id_valid($id) || !is_dir(preview_dir($id))) {
        return ['ok' => false, 'error' => 'Preview not found.'];
    }
    $meta = preview_draft_meta($id);
    $meta['sharing'] = ['enabled' => false, 'expiresAt' => (int)($meta['sharing']['expiresAt'] ?? 0)];
    $meta['updatedAt'] = date('c');
    pak_write(preview_dir($id) . '/draft.json', json_encode($meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
    return ['ok' => true, 'revoked' => true];
}

/**
 * Explicit migration policy for publish:
 *  - 'catalog' (default): catalog entities are copied into MISSING production
 *    files, or MERGED additively (new ids appended, nothing overwritten or
 *    deleted) into existing ones. Transactional rows stay in preview.
 *  - 'all': same, but transactional entities are also copied into MISSING
 *    production files (explicit user request). Existing production files are
 *    never merged for transactional entities and never overwritten for any.
 * Returns a report for meta.json. Never deletes preview data.
 */
function preview_migrate(string $previewAdmin, string $targetAdmin, string $policy = 'catalog'): array {
    $report = ['policy' => $policy, 'copied' => [], 'skipped_existing' => [], 'skipped_policy' => [], 'errors' => []];
    if (!is_dir($previewAdmin)) return $report;
    if (!is_dir($targetAdmin) && !@mkdir($targetAdmin, 0755, true)) {
        $report['errors'][] = 'Cannot create production admin dir.';
        return $report;
    }
    foreach (glob($previewAdmin . '/data_*.json') ?: [] as $pf) {
        $base = basename($pf);
        $eid = preg_replace('/^data_|\.json$/', '', $base);
        $isTxn = preview_is_transactional($eid);
        if ($isTxn && $policy !== 'all') {
            $report['skipped_policy'][] = $base;
            continue;
        }
        $tf = rtrim($targetAdmin, '/') . '/' . $base;
        $rows = json_decode(@file_get_contents($pf), true);
        if (!is_array($rows)) { $report['errors'][] = $base . ' (unreadable, not migrated)'; continue; }
        $rows = array_values($rows);
        if (!is_file($tf)) {
            if (@file_put_contents($tf, json_encode($rows, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE), LOCK_EX) === false) {
                $report['errors'][] = $base . ' (write failed)';
                continue;
            }
            $report['copied'][$base] = count($rows);
            continue;
        }
        if ($isTxn) {
            // Existing production customer data is never merged implicitly.
            $report['skipped_existing'][] = $base;
            continue;
        }
        // Additive catalog merge: new ids appended; existing rows untouched.
        $h = @fopen($tf, 'c+');
        if (!$h) { $report['errors'][] = $base . ' (locked)'; continue; }
        $added = 0;
        try {
            if (!flock($h, LOCK_EX)) { $report['errors'][] = $base . ' (locked)'; }
            else {
                $raw = stream_get_contents($h);
                $prod = ($raw !== false && trim((string)$raw) !== '') ? (json_decode($raw, true) ?: []) : [];
                if (!is_array($prod)) $prod = [];
                $ids = [];
                foreach ($prod as $pr) { if (is_array($pr) && isset($pr['id'])) $ids[(string)$pr['id']] = true; }
                foreach ($rows as $r) {
                    if (!is_array($r) || !isset($r['id']) || isset($ids[(string)$r['id']])) continue;
                    $prod[] = $r;
                    $added++;
                }
                if ($added > 0) {
                    if (count($prod) > 2000) $prod = array_slice($prod, -2000);
                    ftruncate($h, 0);
                    rewind($h);
                    fwrite($h, json_encode(array_values($prod), JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
                    fflush($h);
                }
            }
        } finally {
            flock($h, LOCK_UN);
            fclose($h);
        }
        $report['merged'][$base] = $added;
    }
    return $report;
}

/**
 * Live self-test: request a private file over HTTP. Pass = anything but 200
 * (gate 404/410 or htaccess 403). Transport failure = unverified (honest).
 */
function preview_probe_private(string $id): array {
    $base = defined('SITE_URL') ? rtrim(SITE_URL, '/') : '';
    if ($base === '') return ['pass' => false, 'verified' => false, 'detail' => 'SITE_URL unset'];
    $ctx = stream_context_create(['http' => ['method' => 'GET', 'timeout' => 8,
        'ignore_errors' => true]]);
    $body = @file_get_contents($base . '/preview/' . $id . '/admin/.auth.json', false, $ctx);
    $code = 0;
    foreach ($http_response_header ?? [] as $h) {
        if (preg_match('#^HTTP/\S+\s+(\d+)#', $h, $m)) { $code = (int)$m[1]; break; }
    }
    if ($body === false && $code === 0) {
        return ['pass' => false, 'verified' => false, 'detail' => 'loopback unavailable — verify manually'];
    }
    if ($code === 200) {
        return ['pass' => false, 'verified' => true, 'detail' => 'EXPOSED over HTTP (status 200)'];
    }
    return ['pass' => true, 'verified' => true, 'detail' => 'denied (HTTP ' . $code . ')'];
}

/**
 * Production preflight: same honesty as preview readiness, run against a
 * published site dir after deployment. Returns checks for meta.json —
 * warn-only, never blocks a working deploy.
 */
function production_preflight(string $targetDir, bool $needsAdmin, array $entities = []): array {
    $checks = [];
    $add = function (string $key, string $label, bool $pass, string $detail = '') use (&$checks) {
        $checks[] = ['key' => $key, 'label' => $label, 'pass' => $pass, 'detail' => $detail];
    };
    $idx = is_file($targetDir . '/index.html') ? (string)@file_get_contents($targetDir . '/index.html') : '';
    $add('site', 'Site deployed', strlen($idx) > 100, strlen($idx) . ' bytes');
    $add('handlers', 'Form handlers deployed',
        is_file($targetDir . '/submit.php') || is_file($targetDir . '/contact.php') || is_file($targetDir . '/api/business-ops.php'),
        'submit/contact/api bridge');
    if ($needsAdmin) {
        $adminDir = rtrim($targetDir, '/') . '/admin';
        $missing = [];
        foreach (['login.php', 'index.php', 'inbox.php', 'settings.php', 'api.php',
                  'includes/auth.php', 'includes/db.php', 'includes/layout.php'] as $rel) {
            if (!is_file($adminDir . '/' . $rel)) $missing[] = $rel;
        }
        foreach ($entities as $e) {
            $eid = is_array($e) ? (string)($e['id'] ?? '') : (string)$e;
            if ($eid !== '' && !is_file($adminDir . '/' . $eid . '.php')) $missing[] = $eid . '.php';
        }
        $add('pages', 'Admin pages deployed', empty($missing), empty($missing) ? 'ok' : ('missing: ' . implode(', ', $missing)));
        $auth = is_file($adminDir . '/.auth.json') ? (json_decode(@file_get_contents($adminDir . '/.auth.json'), true) ?: []) : [];
        $hash = (string)($auth['hash'] ?? '');
        $add('auth', 'Admin credentials present',
            $hash !== '' && (str_starts_with($hash, '$2y$') || str_starts_with($hash, '$argon2')), 'hash-only');
        $badData = [];
        foreach (glob($adminDir . '/data_*.json') ?: [] as $df) {
            $raw = trim((string)@file_get_contents($df));
            if ($raw === '' || $raw === '[]') continue;
            if (!is_array(json_decode($raw, true))) $badData[] = basename($df);
        }
        $add('data', 'Production JSON tables valid', empty($badData), empty($badData) ? 'ok' : implode(', ', $badData));
    }
    $ready = true;
    foreach ($checks as $c) { if (!$c['pass']) { $ready = false; break; } }
    return ['ready' => $ready, 'checks' => $checks];
}

